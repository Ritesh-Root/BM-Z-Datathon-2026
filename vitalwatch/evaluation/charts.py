"""Static charts for the README and pitch deck (PNG, light surface).

Design: VitalWatch is the one highlighted series (IBM Carbon blue 60); bedside
scores are de-emphasised gray with direct labels, so identity never relies on
colour alone. Thin marks, solid hairline grid, IBM Plex Sans, no emoji.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from matplotlib import font_manager  # noqa: E402
from matplotlib.patches import Patch  # noqa: E402
from matplotlib.ticker import MaxNLocator  # noqa: E402

FONT_DIR = Path(__file__).resolve().parent.parent / "web" / "static" / "brand" / "fonts" / "ttf"
BLUE = "#0f62fe"       # Carbon blue 60: VitalWatch
GRAY = "#8d8d8d"       # Carbon gray 50: bedside scores / context (de-emphasised)
TEXT = "#161616"       # Carbon gray 100: primary text
TEXT_2 = "#525252"     # Carbon gray 70: secondary text
GRID = "#e0e0e0"       # Carbon gray 20: hairline grid
SURFACE = "#ffffff"
GE = "≥"
NAMES = {"news2": "NEWS2", "qsofa": "qSOFA", "sirs": "SIRS"}


def _style() -> None:
    fonts = list(FONT_DIR.glob("*.ttf"))
    for f in fonts:
        font_manager.fontManager.addfont(str(f))
    plt.rcParams.update({
        "font.family": ["IBM Plex Sans"] if fonts else ["DejaVu Sans"], "font.size": 11,
        "axes.edgecolor": GRID, "axes.linewidth": 1.0, "axes.labelcolor": TEXT_2, "axes.labelpad": 8,
        "axes.titlecolor": TEXT, "axes.titlesize": 14, "axes.titleweight": "medium",
        "axes.titlelocation": "left", "axes.titlepad": 14,
        "xtick.color": TEXT_2, "ytick.color": TEXT_2, "xtick.major.size": 0, "ytick.major.size": 0,
        "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8, "grid.linestyle": "-",
        "axes.spines.top": False, "axes.spines.right": False, "axes.spines.left": False,
        "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
        "legend.frameon": False, "legend.fontsize": 10, "legend.labelcolor": TEXT_2,
    })


def _figure(w: float = 8.4, h: float = 5.0, left: float = 0.11):
    fig = plt.figure(figsize=(w, h))
    ax = fig.add_axes((left, 0.2, 0.97 - left, 0.68))
    return fig, ax


def _footer(fig, source: str, left: float = 0.11) -> None:
    note = ("Synthetic ICU data generated by VitalWatch (not real patients); held-out test patients."
            if source == "synthetic" else "PhysioNet/CinC Challenge 2019 data; held-out test patients.")
    fig.text(left, 0.02, note, fontsize=8.5, color=TEXT_2, ha="left", va="bottom")


def _save(fig, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=200)
    plt.close(fig)


def burden_vs_sensitivity(r: dict, out: Path) -> None:
    fig, ax = _figure(8.4, 5.6)
    cur = r["curves_test"]
    xmax = max(260.0, max(b["test"]["alerts_per_100_patient_days"] for b in r["baselines_matched_burden"]) * 1.15)
    m = sorted((d for d in cur["model"] if d["burden"] <= xmax), key=lambda d: d["burden"])
    ax.plot([d["burden"] for d in m], [100 * d["sensitivity_early"] for d in m], color=BLUE, lw=2,
            solid_capstyle="round", solid_joinstyle="round", label="VitalWatch (any threshold)", zorder=3)

    for key in ("news2", "qsofa", "sirs"):
        pts = sorted((d for d in cur[key] if d["burden"] <= xmax), key=lambda d: d["burden"])
        if key == "news2":
            ax.plot([d["burden"] for d in pts], [100 * d["sensitivity_early"] for d in pts], color=GRAY,
                    lw=1.5, zorder=2, label="Bedside scores (labelled points)")
        ax.scatter([d["burden"] for d in pts], [100 * d["sensitivity_early"] for d in pts], s=40,
                   color=GRAY, edgecolor=SURFACE, linewidth=2, zorder=4)

    placed: list[tuple[float, float]] = []
    for b in sorted(r["baselines_matched_burden"], key=lambda b: b["test"]["alerts_per_100_patient_days"]):
        x, y = b["test"]["alerts_per_100_patient_days"], 100 * b["test"]["sensitivity_early"]
        if x > xmax:
            continue
        near = any(abs(x - px) < 0.15 * xmax and abs(y - py) < 8 for px, py in placed)
        dx, dy, ha = (0, -20, "center") if near else (6, -16, "left")
        ax.annotate(f"{NAMES[b['baseline']]} {GE} {b['threshold']}", (x, y), xytext=(dx, dy),
                    textcoords="offset points", fontsize=9, color=TEXT_2, ha=ha)
        placed.append((x, y))

    sel = r["selected_policy"]["test"]
    sx, sy = sel["alerts_per_100_patient_days"], 100 * sel["sensitivity_early"]
    ax.scatter([sx], [sy], s=120, color=BLUE, edgecolor=SURFACE, linewidth=2.5, zorder=5)
    ax.annotate("VitalWatch alert policy\n(settings chosen on validation)", (sx, sy),
                xytext=(sx + 0.16 * xmax, 12), textcoords="data", fontsize=9.5, color=TEXT,
                fontweight="medium", va="bottom",
                arrowprops=dict(arrowstyle="-", color=TEXT_2, lw=0.8, shrinkA=2, shrinkB=7))
    ax.set_xlim(0, xmax)
    ax.set_ylim(0, 100)
    ax.set_xlabel("Alerts per 100 patient-days (alarm burden)")
    ax.set_ylabel("Septic patients flagged before onset (%)")
    ax.set_title("More septic patients caught early for the same number of alarms")
    ax.legend(loc="lower right")
    _footer(fig, r["source"])
    _save(fig, out)


def matched_burden(r: dict, out: Path) -> None:
    rows = [b for b in r["baselines_matched_burden"] if "vitalwatch_test" in b]
    fig, ax = _figure(8.4, 5.2)
    x = np.arange(len(rows))
    w = 0.3
    base = [100 * b["test"]["sensitivity_early"] for b in rows]
    vw = [100 * b["vitalwatch_test"]["sensitivity_early"] for b in rows]
    ax.bar(x - w / 2 - 0.015, base, w, color=GRAY, label="Bedside score", zorder=3)
    ax.bar(x + w / 2 + 0.015, vw, w, color=BLUE, label="VitalWatch, same or fewer alerts", zorder=3)
    for i in range(len(rows)):
        ax.text(x[i] - w / 2 - 0.015, base[i] + 1.5, f"{base[i]:.0f}%", ha="center", fontsize=9, color=TEXT_2)
        ax.text(x[i] + w / 2 + 0.015, vw[i] + 1.5, f"{vw[i]:.0f}%", ha="center", fontsize=9, color=TEXT,
                fontweight="medium")
    labels = [f"{NAMES[b['baseline']]} {GE} {b['threshold']}\n"
              f"{b['test']['alerts_per_100_patient_days']:.0f} vs {b['vitalwatch_test']['alerts_per_100_patient_days']:.0f} alerts"
              for b in rows]
    ax.set_xticks(x, labels, fontsize=9)
    ax.set_ylim(0, 115)
    ax.set_yticks([0, 20, 40, 60, 80, 100])
    ax.set_ylabel("Septic patients flagged before onset (%)")
    ax.grid(axis="x", visible=False)
    ax.set_title("Head to head at matched alarm burden (alerts per 100 patient-days)")
    ax.legend(loc="upper left", ncol=2, bbox_to_anchor=(0, 1.02))
    _footer(fig, r["source"])
    _save(fig, out)


def lead_time_hist(r: dict, out: Path) -> None:
    rel = -np.array(r["lead_times_test"], dtype=float)  # negative = before onset
    fig, ax = _figure(8.4, 4.8)
    bins = np.arange(-12.5, 4.5, 1.0)
    counts, edges = np.histogram(np.clip(rel, -12, 3), bins=bins)
    centers = (edges[:-1] + edges[1:]) / 2
    ax.bar(centers, counts, width=0.78, color=[BLUE if c <= 0 else GRAY for c in centers], zorder=3)
    ax.axvline(0.5, color=TEXT_2, lw=1, zorder=2)
    top = max(counts.max(), 1)
    ax.set_ylim(0, top * 1.22)
    ax.text(0.5, top * 1.2, "sepsis onset", fontsize=9, color=TEXT_2, va="top", ha="center",
            bbox=dict(facecolor=SURFACE, edgecolor="none", pad=1.5))
    med = float(np.median(-rel)) if len(rel) else 0.0
    ax.yaxis.set_major_locator(MaxNLocator(integer=True))
    ax.set_xticks(range(-12, 4, 2), [f"{-t} h before" if t < 0 else ("onset" if t == 0 else f"{t} h after")
                                       for t in range(-12, 4, 2)], fontsize=9)
    ax.set_xlabel("Time of the first VitalWatch alert, relative to sepsis onset")
    ax.set_ylabel("Septic patients")
    ax.grid(axis="x", visible=False)
    ax.set_title(f"First alert arrives a median of {med:.0f} hours before onset")
    _footer(fig, r["source"])
    _save(fig, out)


def global_drivers_chart(meta: dict, out: Path, source: str) -> None:
    d = meta["global_drivers"][:12][::-1]
    fig, ax = _figure(8.4, 5.6, left=0.27)
    y = np.arange(len(d))
    ax.barh(y, [r["mean_abs_logit"] for r in d], height=0.6,
            color=[BLUE if r["clinical"] else GRAY for r in d], zorder=3)
    ax.set_yticks(y, [r["label"] for r in d])
    ax.grid(axis="y", visible=False)
    ax.set_xlabel("Average influence on the risk score (mean |SHAP|, log-odds)")
    ax.set_title("What drives the risk score")
    ax.legend(handles=[Patch(color=BLUE, label="Clinical signal, shown to nurses"),
                       Patch(color=GRAY, label="Context or care process, never shown as a driver")],
              loc="lower right")
    note = ("Synthetic ICU data generated by VitalWatch (not real patients); validation patients."
            if source == "synthetic" else "PhysioNet/CinC Challenge 2019; validation patients.")
    fig.text(0.27, 0.02, note, fontsize=8.5, color=TEXT_2)
    _save(fig, out)


def calibration_chart(eval_npz: Path, out: Path, source: str) -> None:
    from .evaluate import load_eval, patients_for

    ev = load_eval(eval_npz)
    ys, ss = [], []
    for pt in patients_for(ev, "test"):
        end = int(min(pt["n_hours"] - 1, pt["t_onset"] + 3)) + 1 if pt["septic"] else pt["n_hours"]
        ys.append(pt["labels"][:end])
        ss.append(pt["scores"]["model"][:end])
    y, s = np.concatenate(ys).astype(float), np.concatenate(ss)
    qs = np.quantile(s, np.linspace(0, 1, 11))
    idx = np.clip(np.searchsorted(qs, s, side="right") - 1, 0, 9)
    pred = [100 * s[idx == i].mean() for i in range(10)]
    obs = [100 * y[idx == i].mean() for i in range(10)]
    fig, ax = _figure(6.4, 5.8, left=0.14)
    lim = max(max(pred), max(obs)) * 1.12
    ax.plot([0, lim], [0, lim], color=GRAY, lw=1, zorder=2)
    ax.plot(pred, obs, color=BLUE, lw=2, marker="o", markersize=8, markeredgecolor=SURFACE,
            markeredgewidth=2, zorder=3)
    ax.text(lim * 0.97, lim * 0.9, "perfect calibration", color=TEXT_2, fontsize=9, ha="right")
    ax.set_xlim(0, lim)
    ax.set_ylim(0, lim)
    ax.set_xlabel("Predicted risk (%), deciles of patient-hours")
    ax.set_ylabel("Observed sepsis-label rate (%)")
    ax.set_title("Displayed risk tracks observed risk")
    note = "Synthetic data; held-out test patients." if source == "synthetic" else "PhysioNet 2019; held-out test patients."
    fig.text(0.14, 0.02, note, fontsize=8.5, color=TEXT_2)
    _save(fig, out)


def make_all(results_dir: Path, artifacts_dir: Path, eval_npz: Path, source: str) -> list[str]:
    _style()
    r = json.loads((results_dir / f"metrics_{source}.json").read_text())
    meta = json.loads((artifacts_dir / "model_meta.json").read_text())
    d = results_dir / "charts"
    made = []
    for name, fn in [("burden_vs_sensitivity", lambda p: burden_vs_sensitivity(r, p)),
                     ("matched_burden", lambda p: matched_burden(r, p)),
                     ("lead_time", lambda p: lead_time_hist(r, p)),
                     ("global_drivers", lambda p: global_drivers_chart(meta, p, source)),
                     ("calibration", lambda p: calibration_chart(eval_npz, p, source))]:
        path = d / f"{name}_{source}.png"
        fn(path)
        made.append(str(path))
    return made
